-- Student Management System - PostgreSQL schema
-- (Reference copy. The backend creates these tables automatically on first start
--  via spring.jpa.hibernate.ddl-auto=update, so you do NOT need to run this file.)
--
-- Run once before starting the backend:
--   CREATE DATABASE studentdb;

-- 1. Login accounts (both roles)
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,              -- BCrypt hash, never plain text
    role          VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT users_role_check CHECK (role IN ('STUDENT', 'TEACHER'))
);

-- 2. Student profile with the running point total (one per STUDENT user)
CREATE TABLE student_profiles (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT  NOT NULL,
    total_points INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uk_student_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_student_profiles_user FOREIGN KEY (user_id) REFERENCES users (id)
);
CREATE INDEX idx_student_profiles_points ON student_profiles (total_points);

-- 3. History of every award / deduction made by a teacher
CREATE TABLE point_transactions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT  NOT NULL,
    teacher_id BIGINT  NOT NULL,
    points     INTEGER NOT NULL,                       -- positive = award, negative = deduct
    reason     VARCHAR(255),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_point_tx_student FOREIGN KEY (student_id) REFERENCES student_profiles (id),
    CONSTRAINT fk_point_tx_teacher FOREIGN KEY (teacher_id) REFERENCES users (id)
);

